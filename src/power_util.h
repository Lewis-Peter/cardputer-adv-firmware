// 充电状态推测：Cardputer ADV 的充电 IC 是 TP4057，没有电流传感、CHRG 状态脚也没接到
// 主控，所以 M5.Power.isCharging() 在本机恒为 charge_unknown、getBatteryCurrent() 恒为 0
//（M5 官方明确：本机读不到充电状态/电流）。这里只能靠 G10 的电池电压趋势来"猜"充电：
// 定期采样电压做平滑，看一个时间窗内的斜率——上升判为充电、下降判为放电、走平则保持原状态
//（插上充电线会有一次明显抬升、拔掉通常有明显回落，正好被斜率捕捉）。满电涓流阶段拔线的
// 回落可能很小、捕捉不到，靠一个超时兜底：充电态太久没再出现上升沿就强制退出，见 .cpp。
//
// 电量百分比推测：M5Unified 自带的 getBatteryLevel() 在这块板子上就是一条 3.3V~4.15V 的
// 线性映射，参考了 Bruce 固件（BruceDevices/firmware）的实现后确认它们对同款板子也是同一
// 套线性公式甚至干脆不接——都没有解决"单节LiPo中段电压曲线很平"和"开机上电涌流导致电压
// 瞬时下沉"这两个问题。本文件在此基础上做了两点改进，见 .cpp：非线性查表 + 开机去抖。
#pragma once
#include <cstdint>

void powerUpdate();      // 每帧调用（内部限流采样）
bool powerCharging();    // 当前充电推测（true=在充电）
// 电量百分比推测，替代 M5.Power.getBatteryLevel()。0-100；-1 = 读不到电压、电量未知。
// 返回类型是有符号的 int 不是 uint8_t：调用方（电池详情页、状态栏电池图标、LED 电量指示）
// 都写了 lvl<0 的"未知"分支，用无符号类型会让那些分支永远进不去，读不到电压时反而
// 拿一个编出来的百分比当真的显示。
int powerBatteryLevel();
// 当前平滑后的电池电压(mV)，-1=还没采到。给 Debug 状态条用——**拔线之后串口是断的，
// 屏幕是唯一能看见这两个数的地方**，而标定电量恰恰要在拔线状态下做。
int powerBatteryMv();
// 最近一次采样窗口的峰峰值(mV)。见 .cpp：它能区分"正在快充"和"插着已充满"。
int powerBatterySpread();

// 诊断：连采 n 次原始电压，把分布打到串口（串口 BATT 指令）。
// 这块板子没有电流传感，电量只能从一个被负载污染的电压反推——想改进先得看清噪声本身。
void powerDiag(int n);
