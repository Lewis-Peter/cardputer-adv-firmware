// 汇率：美元 / 人民币，带走势。
//
// 数据源：frankfurter（欧洲央行的参考汇率，免 key、不限流）。
// 选它最主要的理由是**一个请求就能拿整段时间序列**：
//     https://api.frankfurter.dev/v1/2026-08-03..2026-09-02?from=USD&to=CNY
// 画 30 天走势图不需要发 30 次请求。对这块没有 PSRAM、每次 TLS 握手都要抢 40KB
// 连续堆的板子来说，请求次数就是成本本身。
//
// ⚠️ 两条得写在前面的局限：
//   1. 欧洲央行只在 TARGET 工作日公布，周末和假日**没有点**。所以横轴是"第几个交易日"
//      而不是"第几天"，等距画出来的折线在周末处是压缩的。日期标签照实显示。
//   2. 这是**参考汇率**，不是银行结售汇价。跟你在 App 里换汇看到的价差几个点是正常的。
//
// ⚠️⚠️ 解析器（fxParse）是照着接口文档写的，**还没有对过真实响应**——这台机器的出口
// 代理把所有免 key 汇率接口都拦了。字段名或层级如果有出入，只需要改 fxParse 一个函数。
#pragma once
#include "globals.h"

void fxEnter();
void fxExit();
void fxUpdate();
void fxKey(char k);
void drawFx();        // 第1页：现价 + 日变化 + 走势图
void drawFxDays();    // 第2页：最近若干个交易日的收盘列表

// 拼出当前窗口对应的请求 URL。给串口的 FXDUMP 用——它必须打**同一条** URL，
// 否则"照着 dump 的形状写了解析器却还是不工作"就成了新的谜题。
void fxBuildUrl(char* out, size_t n);

// 当前解出多少个数据点。给 tools/uisim 的自检用：它拿同一份数据的两种响应形状各跑一遍，
// 要求解出的点数一致——解析器没对过真响应，这是唯一能钉住"形状容忍"的办法。
int fxPointCount();
